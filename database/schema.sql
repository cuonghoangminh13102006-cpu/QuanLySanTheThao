--Cơ sở dữ liệu--
-- 1. Tạo Database
CREATE DATABASE quan_ly_san_the_thao;
GO
USE quan_ly_san_the_thao;
GO

-- 2. Bảng TAIKHOAN
CREATE TABLE TAIKHOAN (
    MaTaiKhoan INT IDENTITY(1,1) PRIMARY KEY,
    HoVaTen NVARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(20),
    Email VARCHAR(100) NOT NULL UNIQUE,
    MatKhau VARCHAR(255) NOT NULL,
    VaiTro NVARCHAR(50) NOT NULL -- Khách hàng, Chủ sân, Admin
);

-- 3. Bảng COSO
CREATE TABLE COSO (
    MaCoSo INT IDENTITY(1,1) PRIMARY KEY,
    TenCoSo NVARCHAR(150) NOT NULL,
    DiaChi NVARCHAR(255) NOT NULL
);

-- 4. Bảng LOAISAN
CREATE TABLE LOAISAN (
    MaLoaiSan INT IDENTITY(1,1) PRIMARY KEY,
    TenLoaiSan NVARCHAR(100) NOT NULL
);

-- 5. Bảng SAN
CREATE TABLE SAN (
    MaSan INT IDENTITY(1,1) PRIMARY KEY,
    TenSan NVARCHAR(150) NOT NULL,
    HinhAnh VARCHAR(255),
    GioMoCua TIME,
    GioDongCua TIME,
    TrangThai NVARCHAR(50),
    DiaChi NVARCHAR(255),
    Gia DECIMAL(12, 2) NOT NULL,
    SoDienThoai VARCHAR(20),
    ThongTin NVARCHAR(MAX),
    DichVu NVARCHAR(MAX),
    DieuKhoanVaqQuyDinh NVARCHAR(MAX),
    DanhGia DECIMAL(3, 2) DEFAULT 0.0,
    MaCoSo INT NOT NULL,
    FOREIGN KEY (MaCoSo) REFERENCES COSO(MaCoSo) ON DELETE CASCADE
);

-- 6. Bảng trung gian SAN_LOAISAN
CREATE TABLE SAN_LOAISAN (
    MaSan INT NOT NULL,
    MaLoaiSan INT NOT NULL,
    PRIMARY KEY (MaSan, MaLoaiSan),
    FOREIGN KEY (MaSan) REFERENCES SAN(MaSan) ON DELETE CASCADE,
    FOREIGN KEY (MaLoaiSan) REFERENCES LOAISAN(MaLoaiSan) ON DELETE CASCADE
);

-- 7. Bảng NHANVIEN
CREATE TABLE NHANVIEN (
    MaNhanVien INT IDENTITY(1,1) PRIMARY KEY,
    HoVaTen NVARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(20),
    Email VARCHAR(100) NOT NULL UNIQUE,
    TrangThaiLamViec NVARCHAR(50),
    MaCoSo INT NOT NULL,
    FOREIGN KEY (MaCoSo) REFERENCES COSO(MaCoSo) ON DELETE CASCADE
);

-- 8. Bảng DONDATSAN
CREATE TABLE DONDATSAN (
    MaDonDatSan INT IDENTITY(1,1) PRIMARY KEY,
    MaTaiKhoan INT NOT NULL,
    MaSan INT NOT NULL,
    NgayDat DATE NOT NULL,
    GioBatDau TIME NOT NULL,
    GioKetThuc TIME NOT NULL,
    TongTien DECIMAL(12, 2) NOT NULL,
    TrangThaiDon NVARCHAR(50) NOT NULL,
    MaNhanVien INT NOT NULL,
    FOREIGN KEY (MaTaiKhoan) REFERENCES TAIKHOAN(MaTaiKhoan),
    FOREIGN KEY (MaSan) REFERENCES SAN(MaSan),
    FOREIGN KEY (MaNhanVien) REFERENCES NHANVIEN(MaNhanVien)
);

-- 9. Bảng DONHUYSAN
CREATE TABLE DONHUYSAN (
    MaDonHuySan INT IDENTITY(1,1) PRIMARY KEY,
    MaDonDatSan INT NOT NULL,
    ThoiDiemGui DATETIME DEFAULT GETDATE(),
    LyDoHuy NVARCHAR(MAX),
    SoTienHoanLai DECIMAL(12, 2) DEFAULT 0,
    TrangThaiXuLy NVARCHAR(50),
    GhiChu NVARCHAR(MAX),
    MaNhanVien INT NOT NULL,
    FOREIGN KEY (MaDonDatSan) REFERENCES DONDATSAN(MaDonDatSan),
    FOREIGN KEY (MaNhanVien) REFERENCES NHANVIEN(MaNhanVien)
);

-- 10. Bảng GIAODICH
CREATE TABLE GIAODICH (
    MaGiaoDich INT IDENTITY(1,1) PRIMARY KEY,
    MaDonDatSan INT NOT NULL,
    MaDonHuySan INT NULL,
    LoaiGiaoDich NVARCHAR(50) NOT NULL,
    SoTien DECIMAL(12, 2) NOT NULL,
    PhuongThucThanhToan NVARCHAR(50),
    ThoiDiemGiaoDich DATETIME DEFAULT GETDATE(),
    TrangThaiGiaoDich NVARCHAR(50) NOT NULL,
    FOREIGN KEY (MaDonDatSan) REFERENCES DONDATSAN(MaDonDatSan),
    FOREIGN KEY (MaDonHuySan) REFERENCES DONHUYSAN(MaDonHuySan)
);